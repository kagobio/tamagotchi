// Recorrido completo del simulador con clics y botones de verdad. Necesita Playwright:
//   npm i -D playwright && npx playwright install chromium && node simulador/test/flujo.e2e.cjs
const { chromium } = require('playwright');
let failed = 0;
const check = (name, ok, extra = '') => { console.log(ok ? '  ok ' : '  FALLA', name, extra); if (!ok) failed++; };
(async () => {
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1000, height: 1000 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('PAGEERROR ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('file://' + require('path').join(__dirname, '..', 'simulador.html'));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForTimeout(600);
  const box = await page.locator('#screen').boundingBox();
  const click = async (x, y) => { await page.mouse.click(box.x + (x / 240) * box.width, box.y + (y / 280) * box.height); await page.waitForTimeout(120); };
  const S = () => page.evaluate(() => __tinto.view.screen);
  const M = () => page.evaluate(() => ({ stars: __tinto.view.meta.stars, lifetime: __tinto.view.meta.lifetime, owned: Object.keys(__tinto.view.meta.owned), eq: __tinto.view.meta.equipped, plays: __tinto.view.meta.counters.plays }));

  console.log('Tocar la pantalla');
  check('empieza en casa', (await S()) === 'home');
  await click(76, 257);
  check('el icono de jugar abre el menú de juegos', (await S()) === 'hub');
  await click(228, 126);
  await click(12, 126);
  check('las flechas cambian de juego y vuelven', (await page.evaluate(() => __tinto.view.hub.i)) === 0);
  await click(120, 243);
  check('"Jugar" empieza el juego', (await S()) === 'game');
  await click(180, 150);
  await page.evaluate(() => { __tinto.view.game.t = 24.9; });
  await page.waitForTimeout(500);
  check('al acabar sale el resultado', (await S()) === 'result');
  const res = await page.evaluate(() => ({ id: __tinto.view.result.id, plays: __tinto.view.meta.counters.plays, best: __tinto.view.meta.best }));
  check('se cuenta la partida y el logro de la primera', res.plays === 1);
  await click(172, 249);
  check('"Salir" vuelve al menú de juegos', (await S()) === 'hub');
  await click(20, 22);
  check('la flecha atrás vuelve a casa', (await S()) === 'home');

  console.log('Tienda');
  await page.evaluate(() => { __tinto.Meta.award(__tinto.view.meta, 60); });
  await click(120, 257);
  check('el icono de la tienda abre la tienda', (await S()) === 'shop');
  await click(120, 245);
  let m = await M();
  check('comprar el primer sombrero lo compra y lo pone', m.owned.includes('gorro') && m.eq.hat === 'gorro', JSON.stringify({ stars: m.stars }));
  await click(120, 245);
  m = await M();
  check('volver a tocar lo quita', m.eq.hat === null);
  await click(120, 245);
  await click(10 + 58 * 1 + 27, 53);
  await click(120, 245);
  m = await M();
  check('otra pestaña y otro objeto', m.owned.includes('cascabel'));
  await page.evaluate(() => { __tinto.view.meta.stars = 0; });
  await click(228, 128);
  await click(120, 245);
  const msg = await page.evaluate(() => __tinto.view.shopMsg && __tinto.view.shopMsg.text);
  check('sin estrellas no deja comprar', /faltan/.test(msg || ''), msg);
  await click(20, 22);

  console.log('Botones PWR y BOOT');
  await page.evaluate(() => { __tinto.view.menu = 0; __tinto.view.pet.alert = null; __tinto.view.pet.alertQueue = []; });
  await page.click('#pwr');
  check('PWR pasa a la opción siguiente', (await page.evaluate(() => __tinto.view.menu)) === 1);
  await page.click('#boot');
  check('BOOT abre los juegos', (await S()) === 'hub');
  await page.click('#pwr');
  await page.click('#boot');
  check('en el menú de juegos PWR cambia y BOOT juega', (await S()) === 'game' && (await page.evaluate(() => __tinto.view.game.id)) === 'laser');
  await page.evaluate(() => { __tinto.view.game.over = true; });
  await page.waitForTimeout(400);
  check('el resultado sale otra vez', (await S()) === 'result');
  await page.click('#boot');
  check('BOOT en el resultado repite el juego', (await S()) === 'game' && (await page.evaluate(() => __tinto.view.game.id)) === 'laser');
  await click(20, 22);
  check('la X sale del juego y da su resultado', (await page.waitForTimeout(400), (await S()) === 'result'));
  await page.click('#pwr');
  check('PWR en el resultado vuelve al menú de juegos', (await S()) === 'hub');
  await click(20, 22);

  console.log('Estado, concentración y reloj');
  await click(208, 257);
  check('el icono de estado abre el estado', (await S()) === 'info');
  await click(50 + 62 * 1 + 29, 21);
  check('las pestañas cambian', (await page.evaluate(() => __tinto.view.info.tab)) === 1);
  await click(50 + 29, 21);
  await click(68, 250);
  check('"Concentración" empieza la sesión', (await S()) === 'focus');
  await page.evaluate(() => __tinto.setSpeed(600));
  await page.waitForTimeout(3000);
  const f = await page.evaluate(() => ({ done: __tinto.view.focus.done, focus: __tinto.view.meta.counters.focus }));
  check('al acabar el tiempo se completa y cuenta', f.done && f.focus === 1, JSON.stringify(f));
  await page.evaluate(() => __tinto.setSpeed(1));
  await click(120, 246);
  check('"Volver" sale de la concentración', (await S()) === 'home');
  await page.evaluate(() => { __tinto.view.pet.alert = null; __tinto.view.pet.alertQueue = []; });
  await click(208, 257);
  await click(172, 250);
  check('"Reloj" abre el reloj', (await S()) === 'clock');
  await click(120, 140);
  check('tocar el reloj vuelve a casa', (await S()) === 'home');

  console.log('Sorpresas, pasos y guardado');
  await page.evaluate(() => { __tinto.view.pet.surprise = { kind: 'regalo', t: 1, x: 204, y: 206 }; });
  const before = (await M()).stars;
  await click(204, 206);
  check('tocar un regalo da estrellas', (await M()).stars === before + 3);
  const surp = await page.evaluate(() => __tinto.view.meta.counters.surprises);
  check('y se cuenta', surp === 1);
  await page.click('#steps-btn');
  await page.click('#steps-btn');
  const steps = await page.evaluate(() => ({ s: __tinto.view.meta.counters.steps, bank: __tinto.view.meta.counters.stepBank, stars: __tinto.view.meta.stars }));
  check('200 pasos dan una estrella', steps.s === 200 && steps.stars === before + 4, JSON.stringify(steps));
  await page.evaluate(() => { localStorage.setItem('tinto-v2', JSON.stringify(Object.assign({}, __tinto.view.pet))); });
  await page.reload();
  await page.waitForTimeout(600);
  const kept = await M();
  check('al recargar se conserva lo comprado y las estrellas', kept.owned.includes('gorro') && kept.owned.includes('cascabel') && kept.stars === before + 4, JSON.stringify(kept.owned));

  console.log('Reloj por inactividad');
  await page.evaluate(() => { __tinto.go('home'); });
  await page.waitForTimeout(200);
  console.log('errors:', JSON.stringify(errors));
  check('sin errores en la consola', errors.length === 0);
  console.log(failed ? `\n${failed} FALLOS` : '\ntodo bien');
  await browser.close();
  process.exit(failed ? 1 : 0);
})();
